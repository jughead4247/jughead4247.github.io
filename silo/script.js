// =====================================================
// SHARE RESULT
// =====================================================

async function shareResult() {

  const title =
    document.getElementById(
      "result-title"
    ).textContent;


  const knowledge =
    document.getElementById(
      "knowledge-level"
    ).textContent;


  const finalScore =
    document.getElementById(
      "final-score"
    ).textContent;


  const shareText =
    `⚙️ I scored ${finalScore} on the Silo Quiz!\n\n` +
    `${title}\n` +
    `Knowledge level: ${knowledge}\n\n` +
    `How well do YOU know Silo?`;


  const shareData = {

    title:
      "Silo Quiz",

    text:
      shareText,

    url:
      "https://apocalypsequizzes.com/silo-knowledge/"

  };


  try {

    if (navigator.share) {

      await navigator.share(
        shareData
      );

    } else {

      await navigator.clipboard.writeText(

        shareText +
        "\n\nhttps://apocalypsequizzes.com/silo-knowledge/"

      );


      alert(
        "Your result has been copied! You can paste it anywhere."
      );

    }

  }

  catch (error) {

    console.log(
      "Sharing cancelled."
    );

  }

}


// =====================================================
// GLOBAL MENU
// =====================================================

const menuToggle =
  document.getElementById(
    "menu-toggle"
  );


const siteMenu =
  document.getElementById(
    "site-menu"
  );


if (
  menuToggle &&
  siteMenu
) {

  menuToggle.addEventListener(
    "click",
    function(event) {

      event.stopPropagation();


      const isOpen =
        menuToggle.getAttribute(
          "aria-expanded"
        ) === "true";


      siteMenu.hidden =
        isOpen;


      menuToggle.setAttribute(
        "aria-expanded",
        String(!isOpen)
      );


      menuToggle.setAttribute(
        "aria-label",
        isOpen
          ? "Open navigation"
          : "Close navigation"
      );

    }
  );


  document.addEventListener(
    "click",
    function(event) {

      if (
        !siteMenu.hidden &&
        !siteMenu.contains(event.target) &&
        !menuToggle.contains(event.target)
      ) {

        siteMenu.hidden =
          true;


        menuToggle.setAttribute(
          "aria-expanded",
          "false"
        );


        menuToggle.setAttribute(
          "aria-label",
          "Open navigation"
        );

      }

    }
  );


  siteMenu
    .querySelectorAll("a")
    .forEach(
      function(link) {

        link.addEventListener(
          "click",
          function() {

            siteMenu.hidden =
              true;


            menuToggle.setAttribute(
              "aria-expanded",
              "false"
            );


            menuToggle.setAttribute(
              "aria-label",
              "Open navigation"
            );

          }
        );

      }
    );

}