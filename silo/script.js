// =====================================================
// SHOW RESULT
// =====================================================

function showResult() {

  const score =
    calculatePercentage();


  homeInfo.classList.remove(
  "hidden"
);

  quizScreen.classList.add(
    "hidden"
  );

  resultScreen.classList.remove(
    "hidden"
  );


  document.getElementById(
    "final-score"
  ).textContent =
    `${score}%`;


  let title;
  let description;
  let knowledge;
  let icon;


  // ===================================================
  // RESULT LEVELS
  // ===================================================

  if (score < 30) {

    title =
      "Outside-Level Knowledge";

    description =
      "You may know the basic story, but the secrets of the Silo are still mostly hidden from you.";

    knowledge =
      "Outside-Level Knowledge";

    icon =
      "🌫️";

  }

  else if (score < 50) {

    title =
      "Silo Resident";

    description =
      "You know the main characters and events, but plenty of Silo history and details escaped you.";

    knowledge =
      "Silo Resident";

    icon =
      "🏠";

  }

  else if (score < 65) {

    title =
      "Silo Survivor";

    description =
      "You know the important characters, departments and major events. You could probably make it through a few levels.";

    knowledge =
      "Silo Survivor";

    icon =
      "⚙️";

  }

  else if (score < 80) {

    title =
      "Silo Specialist";

    description =
      "Strong knowledge. You remember a lot of the details surrounding Juliette, Solo, Bernard and the Silo's secrets.";

    knowledge =
      "Silo Specialist";

    icon =
      "🔧";

  }

  else if (score < 95) {

    title =
      "Silo Expert";

    description =
      "Impressive. You remember obscure characters, events and lore across all three seasons.";

    knowledge =
      "Silo Expert";

    icon =
      "🛠️";

  }

  else {

    title =
      "Keeper of the Silo";

    description =
      "You remember almost everything. The Pact, the Safeguard, Silo 17 and the deepest secrets are no match for you.";

    knowledge =
      "Keeper of the Silo";

    icon =
      "⚙️";

  }


  document.getElementById(
    "result-title"
  ).textContent =
    title;


  document.getElementById(
    "result-description"
  ).textContent =
    description;


  document.getElementById(
    "knowledge-level"
  ).textContent =
    knowledge;


  const resultIcon =
    document.getElementById(
      "result-icon"
    );


  if (resultIcon) {

    resultIcon.textContent =
      icon;

  }


  progressBar.style.width =
    "100%";


  window.scrollTo({
    top: 0,
    behavior: "smooth"
  });

}


