let currentQuestion = 0;
let selectedAnswers = new Array(questions.length).fill(null);

const startScreen = document.getElementById("start-screen");
const quizScreen = document.getElementById("quiz-screen");
const resultScreen = document.getElementById("result-screen");
const homeInfo = document.getElementById("home-info");

const startButton = document.getElementById("start-btn");
const restartButton = document.getElementById("restart-btn");
const shareButton = document.getElementById("share-btn");
const challengeButton = document.getElementById("challenge-btn");

const backButton = document.getElementById("back-btn");
const nextButton = document.getElementById("next-btn");
const submitButton = document.getElementById("submit-btn");

const questionNumber = document.getElementById("question-number");
const questionText = document.getElementById("question");
const answersContainer = document.getElementById("answers");
const progressBar = document.getElementById("progress-bar");

startButton.addEventListener("click", startQuiz);
restartButton.addEventListener("click", restartQuiz);
shareButton.addEventListener("click", shareResult);
challengeButton.addEventListener("click", shareResult);

backButton.addEventListener("click", goBack);
nextButton.addEventListener("click", goNext);
submitButton.addEventListener("click", showResult);

function startQuiz() {
currentQuestion = 0;
selectedAnswers = new Array(questions.length).fill(null);

startScreen.classList.add("hidden");
resultScreen.classList.add("hidden");
quizScreen.classList.remove("hidden");
homeInfo.classList.add("hidden");

showQuestion();

}

function showQuestion() {

const current = questions[currentQuestion];

questionNumber.textContent =
    `Question ${currentQuestion + 1} of ${questions.length}`;

questionText.textContent = current.question;

answersContainer.innerHTML = "";

const progress =
    ((currentQuestion + 1) / questions.length) * 100;

progressBar.style.width = `${progress}%`;

current.answers.forEach((answer, index) => {

    const button = document.createElement("button");

    button.className = "answer";
    button.type = "button";
    button.textContent = answer[0];

    if (selectedAnswers[currentQuestion] === index) {
        button.classList.add("selected");
    }

    button.addEventListener("click", () => {
        selectAnswer(index);
    });

    answersContainer.appendChild(button);
});

updateNavigation();

}

function selectAnswer(answerIndex) {

selectedAnswers[currentQuestion] = answerIndex;

const buttons =
    answersContainer.querySelectorAll(".answer");

buttons.forEach((button, index) => {
    button.classList.toggle(
        "selected",
        index === answerIndex
    );
});

updateNavigation();

const questionAtSelection = currentQuestion;

setTimeout(() => {

    if (
        currentQuestion === questionAtSelection &&
        selectedAnswers[questionAtSelection] === answerIndex &&
        currentQuestion < questions.length - 1
    ) {
        currentQuestion++;
        showQuestion();
    }

}, 180);

}

function goNext() {

if (selectedAnswers[currentQuestion] === null) {
    return;
}

if (currentQuestion === questions.length - 1) {

    if (
        selectedAnswers.every(
            answer => answer !== null
        )
    ) {
        showResult();
    }

    return;
}

currentQuestion++;
showQuestion();

}

function goBack() {

if (currentQuestion > 0) {
    currentQuestion--;
    showQuestion();
}

}

function updateNavigation() {

const isFirst =
    currentQuestion === 0;

const isLast =
    currentQuestion === questions.length - 1;

const currentAnswered =
    selectedAnswers[currentQuestion] !== null;

const allAnswered =
    selectedAnswers.every(
        answer => answer !== null
    );

backButton.disabled = isFirst;

if (isLast) {

    nextButton.classList.add("hidden");
    submitButton.classList.remove("hidden");

    submitButton.disabled = !allAnswered;

    submitButton.textContent =
        allAnswered
            ? "SUBMIT"
            : "Answer All Questions";

} else {

    submitButton.classList.add("hidden");
    nextButton.classList.remove("hidden");

    nextButton.textContent = "Next →";
    nextButton.disabled = !currentAnswered;
}

}

function calculateScore() {

let score = 0;

selectedAnswers.forEach(
    (answerIndex, questionIndex) => {

        if (answerIndex !== null) {

            score +=
                questions[questionIndex]
                    .answers[answerIndex][1];
        }
    }
);

return score;

}

function showResult() {

const correctAnswers = calculateScore();

// Convert 30-question score to percentage
const score = Math.round(
    (correctAnswers / questions.length) * 100
);

homeInfo.classList.remove("hidden");
quizScreen.classList.add("hidden");
resultScreen.classList.remove("hidden");

document.getElementById("final-score").textContent = `${score}%`;

let title;
let description;
let knowledge;
let icon;

if (score <= 20) {

    title = "🌱 Borderland Newcomer";
    description =
        "The Borderland is still a mystery to you. Maybe it's time to enter the games again and see how much you remember.";
    knowledge = "Casual Viewer";
    icon = "🌱";

} else if (score <= 40) {

    title = "🎮 Game Participant";
    description =
        "You remember some of Arisu's journey and the major games, but the Borderland still has plenty of surprises for you.";
    knowledge = "Casual Fan";
    icon = "🎮";

} else if (score <= 60) {

    title = "🏖️ Borderland Player";
    description =
        "Not bad! You remember many of the important characters, games and events from Season 2.";
    knowledge = "Good Fan";
    icon = "🏖️";

} else if (score <= 80) {

    title = "♠️ Borderland Survivor";
    description =
        "Impressive! You know the major games, characters and twists of Alice in Borderland Season 2 very well.";
    knowledge = "Dedicated Fan";
    icon = "♠️";

} else if (score <= 96) {

    title = "🃏 Face Card Expert";
    description =
        "Excellent! You remember most of the important details and twists from Season 2.";
    knowledge = "Expert Fan";
    icon = "🃏";

} else {

    title = "👑 Borderland Master";
    description =
        "Perfect score! You survived Season 2 and remembered practically every question thrown at you.";
    knowledge = "Ultimate Fan";
    icon = "👑";
}

document.getElementById("result-title").textContent = title;
document.getElementById("result-description").textContent = description;
document.getElementById("knowledge-level").textContent = knowledge;
document.getElementById("result-icon").textContent = icon;

progressBar.style.width = "100%";

}

function restartQuiz() {

currentQuestion = 0;
selectedAnswers =
    new Array(questions.length).fill(null);

resultScreen.classList.add("hidden");
quizScreen.classList.add("hidden");
startScreen.classList.remove("hidden");
homeInfo.classList.remove("hidden");

progressBar.style.width = "0%";

}

async function shareResult() {

    const title =
        document.getElementById("result-title").textContent;

    const knowledge =
        document.getElementById("knowledge-level").textContent;

    const finalScore =
        document.getElementById("final-score").textContent;

    const quizUrl =
        "https://apocalypsequizzes.com/alice-in-borderland-season-2-quiz/";

    const shareText =
        `🃏 I scored ${finalScore} on the Alice in Borderland Season 2 Quiz!\n\n` +
        `${title}\n` +
        `Knowledge level: ${knowledge}\n\n` +
        `How well do YOU know Alice in Borderland Season 2?`;

    const shareData = {
        title: "Alice in Borderland Season 2 Quiz",
        text: shareText,
        url: quizUrl
    };

    try {

        if (navigator.share) {

            await navigator.share(shareData);

        } else {

            await navigator.clipboard.writeText(
                shareText +
                "\n\n" +
                quizUrl
            );

            alert(
                "Your result has been copied! You can paste it anywhere."
            );
        }

    } catch (error) {

        console.log("Sharing cancelled.");

    }

}

