    const correctAnswers =
        calculateScore();


    const totalQuestions =
        questions.length;


    const incorrectAnswers =
        totalQuestions -
        correctAnswers;


    const score =
        Math.round(
            (correctAnswers /
            totalQuestions) * 100
        );


    const accuracy =
        score;


    /* SCREEN VISIBILITY */

    homeInfo.classList.remove(
        "hidden"
    );

    quizScreen.classList.add(
        "hidden"
    );

