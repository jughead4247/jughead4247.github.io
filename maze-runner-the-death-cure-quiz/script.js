<section class="home-info">

<h2>
    About Maze Runner: The Death Cure
</h2>

<p>
    <em>Maze Runner: The Death Cure</em> is the
    2018 science-fiction action thriller that
    concludes the Maze Runner film trilogy.
    The story follows Thomas and the remaining
    Gladers as they attempt to rescue Minho,
    who has been captured by WCKD and taken to
    the Last City.
</p>

<p>
    The film moves the story away from the original
    Maze and into a heavily fortified city controlled
    by WCKD. Thomas, Newt and Frypan become involved
    with the Right Arm resistance while Jorge,
    Brenda and other allies help them reach the
    Last City.
</p>

<p>
    The central conflict revolves around WCKD's
    attempt to develop a treatment for the Flare
    using the Immunes. Thomas's blood becomes
    particularly important to the search for a cure,
    while the rescue of Minho and the survival of
    the remaining Gladers drive the group's final
    mission.
</p>

<p>
    The movie combines large-scale action with
    character-driven moments involving Thomas,
    Newt, Teresa, Minho and Gally. It also brings
    back important characters from earlier films
    while bringing the main story toward its
    conclusion.
</p>

</section>


