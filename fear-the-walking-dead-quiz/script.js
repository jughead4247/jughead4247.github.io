// ===============================
// START QUIZ
// ===============================

function startQuiz() {

    currentQuestion = 0;

    selectedAnswers =
        new Array(questions.length).fill(null);


    startScreen.classList.add("hidden");

    resultScreen.classList.add("hidden");

    quizScreen.classList.remove("hidden");

    homeInfo.classList.add("hidden");


    showQuestion();
}


// ===============================
// SHOW QUESTION
// ===============================

function showQuestion() {

    const current =
        questions[currentQuestion];


    questionNumber.textContent =
        `Question ${currentQuestion + 1} of ${questions.length}`;


    questionText.textContent =
        current.question;


    answersContainer.innerHTML = "";


    const progress =
        ((currentQuestion + 1) /
            questions.length) * 100;


    progressBar.style.width =
        `${progress}%`;


    current.answers.forEach(
        (answer, index) => {

            const button =
                document.createElement("button");


            button.className =
                "answer";


            button.type =
                "button";


            button.textContent =
                answer[0];


            if (
                selectedAnswers[
                    currentQuestion
                ] === index
            ) {

                button.classList.add(
                    "selected"
                );


                button.style.backgroundColor =
                    "#444";

                button.style.borderColor =
                    "#ffffff";

                button.style.color =
                    "#ffffff";

                button.style.fontWeight =
                    "700";

                button.style.boxShadow =
                    "0 0 0 2px rgba(255,255,255,0.25)";
            }


            button.addEventListener(
                "click",
                () => {

                    selectAnswer(index);

                }
            );


            answersContainer.appendChild(
                button
            );

        }
    );


    updateNavigation();
}


// ===============================
// SELECT ANSWER
// ===============================

function selectAnswer(answerIndex) {

    selectedAnswers[currentQuestion] =
        answerIndex;


    const buttons =
        answersContainer.querySelectorAll(
            ".answer"
        );


    buttons.forEach(
        (button, index) => {

            if (index === answerIndex) {

                button.classList.add(
                    "selected"
                );


                button.style.backgroundColor =
                    "#444";

                button.style.borderColor =
                    "#ffffff";

                button.style.color =
                    "#ffffff";

                button.style.fontWeight =
                    "700";

                button.style.boxShadow =
                    "0 0 0 2px rgba(255,255,255,0.25)";

            } else {

                button.classList.remove(
                    "selected"
                );


                button.style.backgroundColor =
                    "";

                button.style.borderColor =
                    "";

                button.style.color =
                    "";

                button.style.fontWeight =
                    "";

                button.style.boxShadow =
                    "";

            }

        }
    );


    updateNavigation();


    if (
        currentQuestion <
        questions.length - 1
    ) {

        const questionAtSelection =
            currentQuestion;


        setTimeout(
            () => {

                if (
                    currentQuestion ===
                        questionAtSelection &&

                    selectedAnswers[
                        questionAtSelection
                    ] === answerIndex
                ) {

                    currentQuestion++;

                    showQuestion();

                }

            },
            150
        );

    }
}


// ===============================
// NEXT BUTTON
// ===============================

function goNext() {

    if (
        currentQuestion ===
        questions.length - 1
    ) {

        const allAnswered =
            selectedAnswers.every(
                answer => answer !== null
            );


        if (allAnswered) {

            showResult();

        }


        return;
    }


    if (
        selectedAnswers[
            currentQuestion
        ] === null
    ) {

        return;

    }


    currentQuestion++;

    showQuestion();
}


// ===============================
// BACK BUTTON
// ===============================

function goBack() {

    if (currentQuestion > 0) {

        currentQuestion--;

        showQuestion();

    }
}


// ===============================
// NAVIGATION
// ===============================

function updateNavigation() {

    const isFirst =
        currentQuestion === 0;


    const isLast =
        currentQuestion ===
        questions.length - 1;


    const currentAnswered =
        selectedAnswers[
            currentQuestion
        ] !== null;


    const allAnswered =
        selectedAnswers.every(
            answer => answer !== null
        );


    backButton.disabled =
        isFirst;


    if (isLast) {

        nextButton.textContent =
            "SUBMIT";


        nextButton.disabled =
            !allAnswered;


        if (allAnswered) {

            nextButton.classList.add(
                "submit-ready"
            );

        } else {

            nextButton.classList.remove(
                "submit-ready"
            );

        }

    } else {

        nextButton.textContent =
            "Next →";


        nextButton.disabled =
            !currentAnswered;


        nextButton.classList.remove(
            "submit-ready"
        );

    }
}


// ===============================
// CALCULATE SCORE
// ===============================

function calculateScore() {

    let score = 0;


    selectedAnswers.forEach(
        (answerIndex, questionIndex) => {

            if (answerIndex === null) {

                return;

            }


            score +=
                questions[
                    questionIndex
                ].answers[
                    answerIndex
                ][1];

        }
    );


    return score;
}


